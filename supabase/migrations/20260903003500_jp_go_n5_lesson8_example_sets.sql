 case c.example_no when 1 then 'Ngữ cảnh JLPT và cấu trúc cơ bản.' else 'Cách dùng thực tế trong công việc.' end,'generated'
from curated c join public.jp_vocab v on v.level='N5' and v.lesson_no=8 and v.word_jp=c.word_jp
on conflict (vocab_id,example_no) do update set example_type=excluded.example_type,
